#!/usr/bin/env python3
"""Generate PenBundledLibraries.cpp from the local Pencil library documents.

Pencil designs reference built-in libraries through their imports map (for
example {"Y": "pencil:shadcn.lib.pen"}), and node fills then use alias-qualified
variable refs such as "$Y:--primary". The library documents are not embedded in
the referencing design, so the converter ships each library's "variables" table
as a JSON literal compiled into the plugin.

Source of truth: the pencil-shadcn/-lunaris/-nitro/-halo .pen documents. Their
values were verified against Pencil-rendered references (e.g. --muted-foreground
#737373, --muted #f5f5f5, Accent=Orange --primary #ea580c on the
lizhongyue248 home-page). Rerun this script when a library refresh lands.
"""

import argparse
import json
from pathlib import Path

LIBRARIES = ("shadcn", "lunaris", "nitro", "halo")

HEADER = """\
// Copyright (c) 2025-2026, Diracsea12. All Rights Reserved. SPDX-License-Identifier: MIT

// Generated by Tools/generate_pen_bundled_libraries.py from the local Pencil
// library documents (pencil-shadcn/-lunaris/-nitro/-halo .pen). Do not edit by
// hand; rerun the generator when a library refresh lands.

#include "PenBundledLibraries.h"

namespace
{
"""

ACCESSOR = """\
}

namespace PenBundledLibraries
{
\tbool TryGetVariablesJson(const FString& LibraryName, FString& OutJson)
\t{
\t\tconst TCHAR* Json = nullptr;
\t\tif (LibraryName == TEXT("shadcn")) { Json = ShadcnVariablesJson; }
\t\telse if (LibraryName == TEXT("lunaris")) { Json = LunarisVariablesJson; }
\t\telse if (LibraryName == TEXT("nitro")) { Json = NitroVariablesJson; }
\t\telse if (LibraryName == TEXT("halo")) { Json = HaloVariablesJson; }

\t\tif (Json == nullptr)
\t\t{
\t\t\treturn false;
\t\t}
\t\tOutJson = Json;
\t\treturn true;
\t}
}
"""


def compact_variables_json(pen_path: Path) -> str:
    doc = json.loads(pen_path.read_text(encoding="utf-8-sig"))
    variables = doc.get("variables")
    if not isinstance(variables, dict) or not variables:
        raise SystemExit(f"{pen_path}: no variables block")
    text = json.dumps(variables, ensure_ascii=False, separators=(",", ":"))
    if ")PENLIB(" in text:
        raise SystemExit(f"{pen_path}: raw-string delimiter collision")
    return text


def literal_chunks(text: str, chunk_size: int = 8000) -> list[str]:
    # MSVC caps a single string literal at 16380 bytes; adjacent TEXT(...)
    # literals concatenate, so emit the blob in chunks well under the cap.
    return [text[i : i + chunk_size] for i in range(0, len(text), chunk_size)]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--designs-root",
        default=r"G:/UE5/FPSRoguelike/Designs",
        help="Directory holding the pencil-<lib>.pen library documents",
    )
    parser.add_argument(
        "--output",
        default=Path(__file__).resolve().parents[1]
        / "Source/Design2UMGCore/Private/PenBundledLibraries.cpp",
        help="Generated .cpp path (default: plugin source tree)",
    )
    args = parser.parse_args()

    designs_root = Path(args.designs_root)
    parts = [HEADER]
    for lib in LIBRARIES:
        pen_path = designs_root / f"pencil-{lib}.pen"
        blob = compact_variables_json(pen_path)
        joined = " ".join(f'TEXT(R"PENLIB({chunk})PENLIB")' for chunk in literal_chunks(blob))
        parts.append(
            f"\tconst TCHAR* {lib.capitalize()}VariablesJson = {joined};\n\n"
        )
    parts.append(ACCESSOR)

    output = Path(args.output)
    output.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {output} ({output.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
